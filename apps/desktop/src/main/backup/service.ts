/**
 * Backup service — manages local SQLite backups using
 * better-sqlite3's .backup() API for WAL-safe snapshots.
 *
 * Two kinds of backup share the backups directory:
 *  - manual: created by the user (File → Create Backup, "Back up now").
 *            Filename `sekel-backup-<ts>.db`. Never deleted automatically.
 *  - auto:   created by the app as a restore point (before a .spkg import,
 *            before a restore). Filename `sekel-backup-<ts>-auto.db`. Only the
 *            newest AUTO_BACKUP_RETENTION are kept; older ones are pruned each
 *            time a new automatic backup is written.
 *
 * Backups made before the kinds existed have no `-auto` suffix, so they are
 * treated as manual and kept.
 */

import fs from 'node:fs';
import path from 'node:path';
import { app } from 'electron';
import { getDb } from '../db/index';
import { createLogger, consoleTransport, metrics } from '@sekel/observability';

const log = createLogger({ module: 'backup', transports: [consoleTransport] });

export type BackupKind = 'manual' | 'auto';

export interface BackupInfo {
    filename: string;
    filePath: string;
    timestamp: string;
    sizeBytes: number;
    kind: BackupKind;
}

/** How many automatic backups to keep. Manual backups are never pruned. */
export const AUTO_BACKUP_RETENTION = 10;

/** Incomplete `*.tmp` backups older than this are treated as crash leftovers. */
const STALE_TMP_MS = 60 * 60 * 1000;

const BACKUP_PREFIX = 'sekel-backup-';
const AUTO_SUFFIX = '-auto.db';
const TMP_SUFFIX = '.tmp';

/** Matches the filenames generated by makeBackupFilename() (either kind). */
const BACKUP_FILENAME_RE = /^sekel-backup-\d{4}-\d{2}-\d{2}T[\d-]+Z(?:-auto)?\.db$/;

/** Returns the directory where backups are stored. */
export function getBackupDir(): string {
    return path.join(app.getPath('userData'), 'backups');
}

/** Ensures the backup directory exists. */
function ensureBackupDir(): void {
    const dir = getBackupDir();
    if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
    }
}

/** Generates a timestamped backup filename. */
function makeBackupFilename(kind: BackupKind): string {
    const now = new Date();
    const ts = now.toISOString().replace(/[:.]/g, '-');
    return `${BACKUP_PREFIX}${ts}${kind === 'auto' ? AUTO_SUFFIX : '.db'}`;
}

function kindOf(filename: string): BackupKind {
    return filename.endsWith(AUTO_SUFFIX) ? 'auto' : 'manual';
}

/**
 * Resolves a renderer-supplied backup filename to its absolute path inside the
 * backup directory. Returns null for anything that is not a bare backup
 * filename (paths, UNC shares, traversal, foreign names).
 */
export function resolveBackupFile(filename: unknown): string | null {
    if (typeof filename !== 'string' || !BACKUP_FILENAME_RE.test(filename)) {
        log.warn('Rejected invalid backup filename', { filename: String(filename) });
        return null;
    }

    const backupDir = path.resolve(getBackupDir());
    const resolved = path.resolve(backupDir, filename);
    if (path.dirname(resolved) !== backupDir) {
        log.warn('Blocked path escape attempt', { resolved });
        return null;
    }
    return resolved;
}

/**
 * Creates a backup of the current database using better-sqlite3's .backup() API.
 * This is safe to call while the database is in WAL mode and actively in use.
 *
 * The snapshot is written to `<name>.tmp` and renamed into place only once
 * complete, so a crash mid-backup never leaves a truncated file that looks
 * like a valid backup.
 *
 * @param kind    'manual' (user-initiated, never pruned) or 'auto' (restore
 *                point; triggers pruning to AUTO_BACKUP_RETENTION).
 * @param protect Backup filenames that pruning must not delete (e.g. the
 *                backup currently being restored from).
 * @returns Info about the created backup, or null if backup failed.
 */
export async function createBackup(
    kind: BackupKind = 'manual',
    protect: string[] = [],
): Promise<BackupInfo | null> {
    let tmpPath: string | null = null;
    try {
        ensureBackupDir();
        const filename = makeBackupFilename(kind);
        const destPath = path.join(getBackupDir(), filename);
        tmpPath = destPath + TMP_SUFFIX;

        const db = getDb();
        await db.backup(tmpPath);
        fs.renameSync(tmpPath, destPath);
        tmpPath = null;

        const stat = fs.statSync(destPath);
        const info: BackupInfo = {
            filename,
            filePath: destPath,
            timestamp: new Date().toISOString(),
            sizeBytes: stat.size,
            kind,
        };

        log.info('Backup created', { filename, kind, size: formatBytes(stat.size) });
        metrics.increment('backup.created_total');

        if (kind === 'auto') {
            pruneAutoBackups(AUTO_BACKUP_RETENTION, [filename, ...protect]);
        }
        return info;
    } catch (err) {
        log.error('Failed to create backup', { error: err instanceof Error ? err.message : String(err) });
        if (tmpPath) {
            try { fs.rmSync(tmpPath, { force: true }); } catch { /* best effort */ }
        }
        return null;
    }
}

/**
 * Deletes automatic backups beyond the newest `keep`, never touching manual
 * backups or anything listed in `protect`. Also removes `*.tmp` leftovers from
 * backups that crashed more than an hour ago. Best effort — never throws.
 *
 * @returns Filenames that were deleted.
 */
export function pruneAutoBackups(keep: number = AUTO_BACKUP_RETENTION, protect: string[] = []): string[] {
    const dir = getBackupDir();
    const deleted: string[] = [];
    let entries: string[];
    try {
        entries = fs.readdirSync(dir);
    } catch {
        return deleted;
    }

    const protectedNames = new Set(protect);
    // Filenames embed a fixed-width ISO timestamp, so lexical order is chronological.
    const autoBackups = entries
        .filter((f) => BACKUP_FILENAME_RE.test(f) && kindOf(f) === 'auto')
        .sort()
        .reverse();

    for (const filename of autoBackups.slice(keep)) {
        if (protectedNames.has(filename)) continue;
        try {
            fs.unlinkSync(path.join(dir, filename));
            deleted.push(filename);
        } catch (err) {
            log.warn('Failed to prune backup', { filename, error: err instanceof Error ? err.message : String(err) });
        }
    }

    const now = Date.now();
    for (const f of entries) {
        if (!f.startsWith(BACKUP_PREFIX) || !f.endsWith(TMP_SUFFIX)) continue;
        try {
            const full = path.join(dir, f);
            if (now - fs.statSync(full).mtimeMs > STALE_TMP_MS) fs.unlinkSync(full);
        } catch { /* best effort */ }
    }

    if (deleted.length > 0) log.info('Pruned old automatic backups', { count: deleted.length });
    return deleted;
}

/** Lists all available backups sorted newest first. */
export function listBackups(): BackupInfo[] {
    const dir = getBackupDir();
    if (!fs.existsSync(dir)) return [];

    return fs.readdirSync(dir)
        .filter((f) => BACKUP_FILENAME_RE.test(f))
        .map((filename) => {
            const filePath = path.join(dir, filename);
            const stat = fs.statSync(filePath);

            return {
                filename,
                filePath,
                timestamp: stat.mtime.toISOString(),
                sizeBytes: stat.size,
                kind: kindOf(filename),
            };
        })
        .sort((a, b) => b.timestamp.localeCompare(a.timestamp));
}

/** Deletes a specific backup file. */
export function deleteBackup(filename: string): boolean {
    const resolved = resolveBackupFile(filename);
    if (!resolved) return false;

    if (!fs.existsSync(resolved)) return false;
    fs.unlinkSync(resolved);
    log.info('Backup deleted', { filename });
    return true;
}

/** Returns the total size of all backups. */
export function getBackupsTotalSize(): number {
    return listBackups().reduce((sum, b) => sum + b.sizeBytes, 0);
}

// ── Helpers ──────────────────────────────────────────────────────────────────

function formatBytes(bytes: number): string {
    if (bytes < 1024) return `${bytes} B`;
    if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
    return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}
